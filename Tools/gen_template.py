#!/usr/bin/env python3
"""Generate Sources/TendieStudio/Export/TendiesTemplate.swift from a real .tendies.

Usage: gen_template.py <real.tendies> <out.swift>

Every community .tendies we inspected (16 samples from the CAPlayground
community collection) shares byte-identical template files (PosterKit
NSKeyedArchiver plists, Wallpaper.plist, index.xml, assetManifest.caml,
Root_Layer.js). We embed them verbatim instead of re-inventing them.
Only main.caml and assets/ differ per wallpaper, and those are generated
by TendiesExporter. .DS_Store and per-wallpaper files are skipped.
"""
import base64, sys, zipfile, hashlib

src, out = sys.argv[1], sys.argv[2]
z = zipfile.ZipFile(src)
rows = []
for n in z.namelist():
    if n.endswith('/') or 'DS_Store' in n or n.endswith('main.caml'):
        continue
    if '/assets/' in n and not n.endswith('Root_Layer.js'):
        continue
    if n.startswith('descriptors/') is False or n.endswith('LICENSE.txt'):
        continue
    parts = n.split('/', 2)          # descriptors / <uuid> / rest
    uuid, rest = parts[1], parts[2]
    if '/supplements/' in '/' + rest:  # optional in real files; omit
        continue
    rows.append((rest, base64.b64encode(z.read(n)).decode(), hashlib.sha256(z.read(n)).hexdigest()[:12]))
rows.sort()
with open(out, 'w') as f:
    f.write('// GENERATED by Tools/gen_template.py from a real community .tendies. Do not edit.\n')
    f.write('// Paths are relative to descriptors/<UUID>/. Content is base64 of the exact original bytes.\n')
    f.write('import Foundation\n\nenum TendiesTemplate {\n')
    f.write(f'    static let descriptorUUID = "{uuid}"\n')
    f.write('    struct File { let path: String; let base64: String; let sha256Prefix: String\n')
    f.write('        var data: Data { Data(base64Encoded: base64)! } }\n')
    f.write('    static let files: [File] = [\n')
    for p, b, h in rows:
        f.write(f'        File(path: "{p}", base64: "{b}", sha256Prefix: "{h}"),\n')
    f.write('    ]\n}\n')
print(len(rows), 'template files ->', out)
